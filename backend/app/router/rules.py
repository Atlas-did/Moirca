def find_rules(text: str, rules: List[Rule]) -> List[Tuple[Rule, int]]:
    """返回 (rule, 命中次数) 列表;纯函数。"""
    hits: List[Tuple[Rule, int]] = []
    for rule in rules:
        count = sum(1 for kw in rule.keywords if kw and kw in text)
        if count > 0:
            hits.append((rule, count))
    return hits


def count_entities(text: str) -> int:
    """统计不同高考实体词命中数。"""
    return sum(1 for kw in GAOKAO_ENTITY_KEYWORDS if kw in text)


def is_time_sensitive(text: str) -> bool:
    """是否带时间敏感信号(年份/相对时间词)。"""
    if any(kw in text for kw in TIME_SENSITIVE_PATTERN_KEYWORDS):
        return True
    return any(y in text for y in TIME_SENSITIVE_YEAR_PREFIXES)


def platform_mentioned(text: str) -> bool:
    """受控浏览请求里是否已点名平台。"""
    return any(kw in text for kw in CONTROLLED_PLATFORM_KEYWORDS)
